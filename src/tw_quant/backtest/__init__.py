"""台股歷史回測引擎套件 (src/tw_quant/backtest/).

目前完成範圍（第三階段 C-2.1, C-2.2, C-2.3 & C-2.4）：
- `exceptions`: 回測例外階層（含資料缺漏、交易日曆異常、PIT 時序違規、未來資訊洩漏、格式/數值錯誤、資料血統缺失、批次帳務、公司行動、歷史撮合、投資組合估值、預測供給與回測執行器例外）。
- `calendar`: 台灣時區 `Asia/Taipei` 交易日曆 `TradingCalendar`（區分交易日、非交易日與未知日期）。
- `data_provider`: Point-in-Time (PIT) 歷史資料供應器 `HistoricalDataProvider` 與 `InMemoryHistoricalDataProvider`。
- `lot_ledger`: FIFO 持倉批次追蹤帳本 `BacktestLotLedger`、`PositionLot`、`ClosedLotTrade` 與 `LotFillEvent`。
- `corporate_actions`: 除權息與公司行動處理器 `CorporateActionProcessor`、`CorporateActionEvent`、`DividendReceivable` 與 `AccountNAVBreakdown`。
- `simulator`: 歷史日線撮合模擬器 `HistoricalExecutionSimulator`、可注入價格限制規則 `PriceLimitRule` / `TaiwanHistoricalPriceLimitRule`、Tick Size 規則 `TickSizeRule` / `TaiwanTickSizeRule` 與單一責任成交成本模型 `ExecutionCostModel`。
- `valuator`: 每日投資組合估值器 `PortfolioValuator` 與結構化 `DailyNAVRecord`。
- `prediction_feed`: AI 預測批次供給器 `PredictionFeed` / `InMemoryPredictionFeed`、`WalkForwardWindowSpec` 與 `UnverifiedPredictionPolicy`。
- `adapters`: 策略與風控橋接器 `StrategyEngineAdapter`、`RiskEngineAdapter` 與 `BacktestRiskContext`。
- `runner`: 事件驅動 Walk-Forward 歷史回測主迴圈 `WalkForwardRunner`、`WalkForwardRunConfig`、`DailyBacktestLog` 與 `BacktestRunResult`。
"""

